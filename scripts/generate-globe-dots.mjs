// Precomputes the globe's land-dot lattice into components/ui/globe-land-dots.ts.
//
// The globe used to build this at runtime: d3.geoContains() for each of the
// 15,300 points of a 2° lat/lon grid against the full Natural Earth land
// polygons — ~6.5s of main-thread work on a fast laptop, every visit. The
// coastline data never changes, so the answer is baked in here instead, as a
// bitmask with one bit per grid cell (~1.9 KB raw, ~2.6 KB base64).
//
// Run after changing the land data or the grid:
//   node scripts/generate-globe-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";

const STEP = 2;
const LAT_MIN = -84;
const LAT_MAX = 84;
const LON_MIN = -180;
const ROWS = (LAT_MAX - LAT_MIN) / STEP + 1;
const COLS = 360 / STEP;

const land = JSON.parse(readFileSync("public/data/ne_110m_land.json", "utf8"));
const mask = new Uint8Array(Math.ceil((ROWS * COLS) / 8));
let count = 0;

for (let row = 0; row < ROWS; row++) {
  for (let col = 0; col < COLS; col++) {
    const point = [LON_MIN + col * STEP, LAT_MIN + row * STEP];
    if (!geoContains(land, point)) continue;
    const index = row * COLS + col;
    mask[index >> 3] |= 1 << (index & 7);
    count++;
  }
}

const b64 = Buffer.from(mask).toString("base64");
const lines = b64.match(/.{1,76}/g).map((line) => `  "${line}"`).join(" +\n");

writeFileSync(
  "components/ui/globe-land-dots.ts",
  `// GENERATED by scripts/generate-globe-dots.mjs — do not edit by hand.
//
// ${count} land points on a ${STEP}° lat/lon grid (${ROWS} × ${COLS} cells), derived from
// Natural Earth 1:110m land (public domain) in public/data/ne_110m_land.json.
// One bit per cell, row-major from (${LAT_MIN}°, ${LON_MIN}°).

const STEP = ${STEP};
const LAT_MIN = ${LAT_MIN};
const LON_MIN = ${LON_MIN};
const CELLS = ${ROWS * COLS};
const COLS = ${COLS};

const LAND_MASK_B64 =
${lines};

/** Decodes the mask into [longitude, latitude] points. Takes well under 1ms. */
export function decodeLandDots(): Array<[number, number]> {
  const bits = atob(LAND_MASK_B64);
  const dots: Array<[number, number]> = [];
  for (let index = 0; index < CELLS; index++) {
    if (bits.charCodeAt(index >> 3) & (1 << (index & 7))) {
      dots.push([
        LON_MIN + (index % COLS) * STEP,
        LAT_MIN + Math.floor(index / COLS) * STEP,
      ]);
    }
  }
  return dots;
}
`,
);

console.log(`wrote ${count} land dots (${mask.length} bytes, ${b64.length} chars base64)`);
